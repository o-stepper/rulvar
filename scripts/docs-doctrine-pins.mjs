// Doctrine pins over the hand-written docs (RV3901, the fourth
// comparison experiment). The budgets guide taught "immutable after
// start ... resume accepts no budget parameter" for six weeks after
// RV2208 shipped `ResumeOptions.run`; RV2511 corrected the doctrine in
// the budget.ts code comment and nobody corrected the guide, so the
// run synthesized its own answer FROM the stale guide, hedged, never
// named the override API, and lost the correctness score on exactly
// that sentence. A doctrine retired in code must become
// unrepresentable in docs, not merely fixed once: this gate bans the
// proven-stale sentences outright and pins the pages that must name
// the current contract.
//
// Two kinds of pin, both byte-literal on purpose (a paraphrase that
// dodges a regex is a new sentence a reviewer reads fresh):
//   BANNED: phrases no hand-written page may contain, each carrying
//     the RV id that retired the doctrine it states.
//   REQUIRED: per-page patterns that must keep matching, so the pages
//     that document the current contract cannot silently drop it.
//
// Scope: docs/guide, docs/reference, docs/api (RV3902: the source
// TSDoc behind the generated pages is swept, so the generated bytes
// must stay clean too), and README.md. The changelog is a historical
// record generated from changesets and is excluded, the
// docs-role-truth rule.
//
// Usage:
//   node scripts/docs-doctrine-pins.mjs        check (a CI gate)
//
// Run with: pnpm docs:doctrine (and pnpm test:scripts for the tests).
