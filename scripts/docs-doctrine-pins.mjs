/** Judges one page; returns failure strings, empty when clean. */
export function judgeDoctrine(text, where) {
  const failures = [];
  for (const ban of BANNED) {
    if (ban.pattern.test(text)) {
      failures.push(`${where}: contains the retired doctrine "${ban.phrase}" (${ban.why})`);
    }
  }
  for (const pin of REQUIRED) {
    if (pin.file === where && !pin.pattern.test(text)) {
      failures.push(
        `${where}: no longer matches ${String(pin.pattern)}; the pin exists because ${pin.what}`,
      );
    }
  }
  return failures;
}

async function markdownFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((entry) => {
      const path = join(directory, entry.name);
      return entry.isDirectory() ? markdownFiles(path) : path.endsWith('.md') ? [path] : [];
    }),
  );
  return nested.flat();
}

export async function main() {
  const files = [...extraFiles];
  for (const root of docsRoots) {
    files.push(...(await markdownFiles(root)));
  }
  const failures = [];
  const seen = new Set();
  for (const file of files) {
    if (EXCLUDED.has(file)) {
      continue;
    }
    const where = relative(repoRoot, file).replaceAll('\\', '/');
    seen.add(where);
    failures.push(...judgeDoctrine(await readFile(file, 'utf8'), where));
  }
  // A required pin whose page vanished must fail too: deleting the page
  // that carries the contract is the loudest way to drop it.
  for (const pin of REQUIRED) {
    if (!seen.has(pin.file)) {
      failures.push(`${pin.file}: pinned page missing; the pin exists because ${pin.what}`);
    }
  }
  if (failures.length > 0) {
    console.error('[docs-doctrine-pins] the docs contradict the shipped budget doctrine:');
    for (const failure of failures) {
      console.error(`  ${failure}`);
    }
    return 1;
  }
  console.log(
    `[docs-doctrine-pins] ${String(BANNED.length)} banned phrases absent, ` +
      `${String(REQUIRED.length)} required pins present`,
  );
  return 0;
}

// Importing this module for its helpers must never run the gate: the
// tests import it, and a self-running module would scan the repo (and
// exit) on import.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exit(await main());
}
